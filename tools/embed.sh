#!/bin/sh
# Embed static web assets into a C source file (POSIX sh + od + sed only, so
# the build needs no extra tools and the result is still one static binary).
#
#   sh tools/embed.sh OUT.c FILE...
#
# Each FILE becomes a byte array; a table maps its basename ("/index.html",
# "/app.js", ...) to the array, its length and a Content-Type. "/index.html"
# is also served as "/".
set -eu
out=$1; shift
[ $# -gt 0 ] || { echo "usage: embed.sh OUT.c FILE..." >&2; exit 2; }

ctype() {
  case "$1" in
    *.html) echo "text/html; charset=utf-8" ;;
    *.js)   echo "application/javascript; charset=utf-8" ;;
    *.css)  echo "text/css; charset=utf-8" ;;
    *.svg)  echo "image/svg+xml" ;;
    *.png)  echo "image/png" ;;
    *.woff2) echo "font/woff2" ;;
    *.json) echo "application/json" ;;
    *.txt)  echo "text/plain; charset=utf-8" ;;
    *)      echo "application/octet-stream" ;;
  esac
}

tmp="$out.tmp"
{
  echo "/* GENERATED by tools/embed.sh - do not edit. Sources: $* */"
  echo "#include \"web_assets.h\""
  i=0
  for f in "$@"; do
    i=$((i + 1))
    echo "static const unsigned char asset_${i}[] = {"
    # -v: no '*' line squeezing; one byte per token, 16 per line
    od -An -v -tx1 "$f" | sed -e 's/^ *//' -e 's/  */ /g' -e 's/\([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "0x00 };"   # trailing NUL so text assets are also valid C strings
  done
  echo "const web_asset_t web_assets[] = {"
  i=0
  for f in "$@"; do
    i=$((i + 1))
    b=$(basename "$f")
    len=$(wc -c < "$f" | tr -d ' ')
    echo "  { \"/$b\", \"$(ctype "$b")\", asset_${i}, ${len}UL },"
  done
  echo "};"
  echo "const int web_assets_count = $#;"
} > "$tmp"
mv "$tmp" "$out"
echo "embedded $# asset(s) into $out"
